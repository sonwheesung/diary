/**
 * AI 리포트 정책 상수 — **한 곳에서만 정의한다.**
 *
 * `lib/policy.ts`와 같은 규약이다. 흩어지면 하나만 고치고 나머지를 잊는다.
 *
 * ⚠ 앱에도 같은 뜻의 값이 있다(`report.onceAWeek` 안내 문구). **두 값이 같아야 한다** —
 *   화면에는 "주에 한 번"이라 적어놓고 서버가 두 번을 허용하면 사용자는 그걸 버그로 겪는다.
 *   지금 앱은 숫자를 코드로 갖지 않고 문구로만 갖는데, 그건 캡이 1일 때만 성립한다.
 *   **여기를 2 이상으로 올리면 앱 문구도 함께 고친다**(`docs/AI_REPORT_SYSTEM.md` §5).
 */

