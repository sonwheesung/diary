/**
 * AI 리포트 정책 상수 — **한 곳에서만 정의한다.**
 *
 * `lib/policy.ts`와 같은 규약이다. 흩어지면 하나만 고치고 나머지를 잊는다.
 *
 * ⚠ 앱에도 같은 뜻의 값이 있다(`report.onceAWeek` 안내 문구). **두 값이 같아야 한다** —
 *   화면에는 "주에 한 번"이라 적어놓고 서버가 두 번을 허용하면 사용자는 그걸 버그로 겪는다.
 *   지금 앱은 숫자를 코드로 갖지 않고 문구로만 갖는데, 그건 캡이 1일 때만 성립한다.
 *   **여기를 2 이상으로 올리면 앱 문구도 함께 고친다**(`docs/AI_REPORT_SYSTEM.md` §5).
 */

/**
 * 주간 리포트를 **한 주에 몇 번** 만들 수 있는가.
 *
 * 튜닝 대상이라 상수로 뺐다(2026-08-12 사용자 결정: *"주간 주 1회만 하고 계속 튜닝해야지"*).
 * ⚠ 올릴 때 함께 볼 것: 원가(§4)와 앱 문구.
 */
export const WEEKLY_PER_WEEK = 1;

/**
 * 월간·연간의 기간당 횟수.
 *
 * 계층 요약이라 입력(하위 리포트)이 안 바뀌면 결과도 크게 안 바뀐다 — 여러 번 만들 이유가 없다.
 * 기간당 1회면 충분하고, 앱의 `(kind, period_key)` UNIQUE가 이미 같은 것을 강제한다.
 */
export const MONTHLY_PER_MONTH = 1;
export const YEARLY_PER_YEAR = 1;

/**
 * 하루 총 호출 상한 — **폭주 방어**다. 위의 기간별 캡과 목적이 다르다.
 *
 * 기간 캡은 "같은 주를 두 번 만들지 마라"이고, 이건 "버그나 악용으로 하루에 수백 번
 * 부르지 마라"다. 정상 사용자는 여기 닿을 일이 없다 — 주간 1 + 월간 1 + 연간 1이 최대다.
 *
 * ⚠ 이게 없으면 앱의 재시도 루프 하나가 그대로 청구서가 된다.
 *
 * 🔴 **10 → 30 (2026-08-18, 백필과 함께)**. 백필(§6.4)이 열리면 1년치가 65건인데 10이면
 *   7일이 걸려 기능이 사실상 안 열린다. 올려도 안전한 이유는 **총량을 이 값이 정하지 않기**
 *   때문이다 — `uq_ai_usage_period`가 기간마다 평생 1회로 묶으므로 총 노출은 지평이 정하고
 *   (최악 130건 = ₩117), 이 값은 **속도**만 정한다. 폭주 방어는 그대로다(하루 최악 ₩27).
 */
export const DAILY_CALL_CAP = 30;

/**
 * 🔴 **모델을 부른 뒤 실패하면 이만큼 잠근다** (`docs/AI_REPORT_SYSTEM.md` §5.1).
 *
 * 위의 `DAILY_CALL_CAP`은 `ai_usage` 행을 세는데 그 행은 **성공에만** 쓰인다.
 * 즉 실패는 일일 캡에도 안 잡혀 **실패하는 루프가 무제한이었다** — 그런데 비싼 쪽이 실패다
 * (`refused`·`truncated`는 모델이 돌고 나서 실패한 것이라 토큰이 이미 청구됐다).
 *
 * ⚠ **캡이 아니다.** 한 시간 뒤 같은 기간을 그대로 다시 만들 수 있다 —
 *   `ai_usage`에 행이 없으므로 기간 캡은 비어 있다. 잃는 것은 한 시간뿐이다.
 *
 * ⚠ **게이트 실패에는 걸지 않는다.** 비구독·빈 입력은 돈이 안 나갔다.
 *   거기 잠금을 걸면 구독만 끊긴 사람이 한 시간 동안 아무것도 못 한다.
 */
export const FAILURE_COOLDOWN_MS = 60 * 60 * 1000;

/**
 * 입력 길이 상한(문자).
 *
 * ⚠ 토큰이 아니라 **문자**로 센다. 서버에서 토크나이저를 돌리면 그 자체가 비용이고,
 *   여기서 필요한 것은 정확한 과금 계산이 아니라 **터무니없는 입력을 거절하는 것**이다.
 *
 * 한국어 일기 한 편이 대략 200~400자다. 하루 여러 편을 쓰는 사람을 넉넉히 잡아
 * 주당 4만 자면 상식적인 상한을 크게 넘는다.
 */
export const MAX_INPUT_CHARS = 40_000;

/**
 * 모델 응답 상한(토큰). 리포트는 서너 문단이다.
 *
 * ⚠ **추론 토큰이 여기 포함된다.** 너무 조이면 `status: 'incomplete'`로 잘려 돌아오고,
 *   그건 빈 요약과 구별되지 않는다. 넉넉히 두고 원가는 캡으로 통제한다.
 */
export const MAX_OUTPUT_TOKENS = 4000;

/**
 * 진행 중인 멱등 키를 기억하는 시간.
 *
 * ⚠ **결과를 저장하지 않는다** — 무저장 원칙이다. 키와 "처리 중"이라는 사실만 남는다.
 *   그래서 재시도가 중복 과금이 되지 않게 막을 수는 있어도, 놓친 응답을 다시 줄 수는 없다.
 */
export const IN_FLIGHT_TTL_MS = 5 * 60 * 1000;

/**
 * 리포트 본문 보관 기간 — **90일** (2026-08-13 사용자 결정, `docs/AI_REPORT_SYSTEM.md` §5.2).
 *
 * 리포트를 저장하는 목적은 **품질 피드백**이다. 프롬프트를 고칠 근거로 쓰기에 90일이면
 * 충분하고, 그보다 오래 두면 목적을 넘는 보유가 된다.
 *
 * ⚠ **무기한은 처리방침에 쓸 수 없다.** 기간을 정해야 "언제 파기하는지"를 적을 수 있고,
 *   적었으면 실제로 지워야 한다 — 리퍼가 그 약속을 강제한다.
 */
export const REPORT_RETENTION_MS = 90 * 24 * 60 * 60 * 1000;

/**
 * 실패 잠금 기록도 영원히 둘 이유가 없다. 만료된 행은 리퍼가 치운다.
 * ⚠ 잠금 판정은 `until > now`로 하므로 이 정리가 늦어도 동작에는 영향이 없다.
 */
export const COOLDOWN_TTL_MS = 7 * 24 * 60 * 60 * 1000;
